// Testa seleção de até dez armas por fase.
const Sim = require('../shared/sim.js'); const Eco = require('../shared/economy.js');
const ok = (condition, message) => { console.log((condition ? '✅ ' : '❌ ') + message); if (!condition) process.exitCode = 1; };
const now = Date.now(), p = Eco.newPlayer(now); p.unlocked = Sim.TOWER_IDS.slice(0, 14);
const available = Eco.publicView(p, now).owned, selected = available.slice(0, 10);
const started = Eco.startLevel(p, 1, now, false, selected);
ok(started.ok && started.cfg.loadout.length === 10, 'dez armas escolhidas no início da fase');
const state = Sim.createGame(started.cfg);
ok(selected.every(k => Sim.canUse(state, k)), 'dez armas escolhidas são utilizáveis');
const excluded = available.filter(k => !selected.includes(k));
ok(excluded.every(k => !Sim.canUse(state, k)), 'armas não selecionadas ficam bloqueadas');
const next = Eco.startLevel(p, 1, now + 1, false);
ok(next.ok && JSON.stringify(next.cfg.loadout) === JSON.stringify(selected), 'seleção de dez armas salva');
const seven = Eco.startLevel(p, 1, now + 2, false, available.slice(0, 7));
ok(seven.ok && seven.cfg.loadout.length === 7, 'seleção flexível entre uma e dez armas');
const eleven = Eco.startLevel(p, 1, now + 3, false, available.slice(0, 11));
ok(!!eleven.error, 'servidor rejeita onze armas');
const duplicate = Eco.startLevel(p, 1, now + 4, false, [selected[0], selected[0]]);
ok(!!duplicate.error, 'servidor rejeita arma duplicada');
const unknown = Eco.startLevel(p, 1, now + 5, false, ['arma-que-nao-existe']);
ok(!!unknown.error, 'servidor rejeita arma que não pertence à conta');
const oldPlayer = { coins: 123, gems: 7, maxLevel: 4, stars: { 1: 3 } }; Eco.migrate(oldPlayer, now);
ok(oldPlayer.coins === 123 && oldPlayer.maxLevel === 4 && oldPlayer.loadouts, 'conta antiga mantém progresso');
const legacyGame = Sim.createGame({ level: 1, unlocked: available });
ok(available.every(k => Sim.canUse(legacyGame, k)), 'partidas antigas continuam compatíveis');
